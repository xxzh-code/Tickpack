// Tests for the Tickpack mini-simulator.
//
// All packs here are handwritten mcfunction (never imported from src/lang), shaped
// like the compiler output described in docs/LANG.md §2/§3. Run with:
//   node --test test/sim.test.js

import test from 'node:test';
import assert from 'node:assert/strict';

import { Simulator } from '../src/sim/sim.js';

// ---------------------------------------------------------------------------
// helpers
// ---------------------------------------------------------------------------

const P = (rel) => `data/tp/function/${rel}.mcfunction`;

const BASE_LOAD = [
  '# generated by Tickpack',
  'scoreboard objectives add tp dummy',
  'scoreboard players set #__tick tp 0',
  'scoreboard players set #__pc tp 0',
  'scoreboard players set #__sleep tp 0',
  'scoreboard players set #__press tp 0',
  'scoreboard players set #__pressSeen tp 0',
].join('\n');

/** Build a virtual pack: load/tick plus extra function files and optional tags. */
function pack({ load = BASE_LOAD, tick = '', files = {}, tags = null } = {}) {
  const out = { 'pack.mcmeta': '{"pack":{"pack_format":48,"description":"test"}}' };
  out[P('load')] = load;
  out[P('tick')] = tick;
  for (const [rel, text] of Object.entries(files)) out[P(rel)] = text;
  if (tags) {
    for (const [kind, text] of Object.entries(tags)) {
      out[`data/minecraft/tags/function/${kind}.json`] = text;
    }
  }
  return out;
}

function makeSim(options) {
  const sim = new Simulator(pack(options));
  sim.reset();
  return sim;
}

function scoreOf(sim, holder, objective = 'tp') {
  const scores = sim.getScores()[objective] || {};
  return scores[holder] === undefined ? 0 : scores[holder];
}

function byType(events, type) {
  return events.filter((event) => event.type === type);
}

function worldBlocks(sim) {
  return sim.getWorld().blocks;
}

function penOf(sim) {
  return sim.getWorld().entities.find((entity) => entity.tags.includes('pen'));
}

const PEN_SUMMON =
  'summon armor_stand 0.5 0 0.5 {Tags:["pen"],Invisible:1b,NoGravity:1b,Marker:1b}';

