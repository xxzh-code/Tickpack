test('scoreboard math: int32 wraparound, truncating division, div/mod by zero = 0', () => {
  const load = `${BASE_LOAD}\nscoreboard players set #two tp 2\nscoreboard players set #zero tp 0`;
  const sim = makeSim({
    load,
    tick: [
      'scoreboard players set #a tp 2147483647',
      'scoreboard players add #a tp 1',
      'scoreboard players set #b tp -7',
      'scoreboard players operation #b tp /= #two tp',
      'scoreboard players set #c tp -7',
      'scoreboard players operation #c tp %= #two tp',
      'scoreboard players set #d tp 5',
      'scoreboard players operation #d tp /= #zero tp',
      'scoreboard players set #e tp 5',
      'scoreboard players operation #e tp %= #zero tp',
      'scoreboard players set #f tp 100000',
      'scoreboard players operation #f tp *= #f tp',
      'scoreboard players operation #u tp = #nobody tp',
    ].join('\n'),
  });
  sim.step();

  assert.equal(scoreOf(sim, '#a'), -2147483648);
  assert.equal(scoreOf(sim, '#b'), -3); // truncate toward zero
  assert.equal(scoreOf(sim, '#c'), -1);
  assert.equal(scoreOf(sim, '#d'), 0);
  assert.equal(scoreOf(sim, '#e'), 0);
  assert.equal(scoreOf(sim, '#f'), 1410065408); // 10^10 wrapped to int32
  assert.equal(scoreOf(sim, '#u'), 0); // unknown score = 0
});

test('scoreboard operations = += -= *= reset and objectives add/remove', () => {
  const sim = makeSim({
    tick: [
      'scoreboard objectives add foo dummy',
      'scoreboard players set #a foo 10',
      'scoreboard players set #b foo 3',
      'scoreboard players operation #a foo -= #b foo',
      'scoreboard players operation #b foo = #a foo',
      'scoreboard players operation #a foo += #a foo',
      'scoreboard players operation #a foo *= #b foo',
      'scoreboard players reset #b foo',
    ].join('\n'),
  });
  const events = sim.step();
  const foo = sim.getScores().foo;
  assert.ok(foo, 'objective foo should exist');
  assert.equal(foo['#a'], 98); // ((10-3) * 2) * 7 = 98
  assert.equal(foo['#b'], undefined);

  // remove deletes the objective entirely
  const sim2 = makeSim({
    tick: ['scoreboard objectives add bar dummy', 'scoreboard players set #q bar 1', 'scoreboard objectives remove bar'].join('\n'),
  });
  sim2.step();
  assert.equal(sim2.getScores().bar, undefined);
  assert.ok(byType(events, 'command').length >= 8);
});

