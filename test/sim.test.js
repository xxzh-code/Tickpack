test('execute if/unless score matches all range forms — and non-matches run nothing', () => {
  const sim = makeSim({
    tick: [
      'scoreboard players set #n tp 5',
      'execute if score #n tp matches 5 run scoreboard players set #exact tp 1',
      'execute if score #n tp matches 5.. run scoreboard players set #min tp 1',
      'execute if score #n tp matches ..5 run scoreboard players set #max tp 1',
      'execute if score #n tp matches 5..10 run scoreboard players set #range tp 1',
      'execute if score #n tp matches .. run scoreboard players set #all tp 1',
      'execute unless score #n tp matches 6 run scoreboard players set #unless tp 1',
      'execute if score #n tp matches 6 run scoreboard players set #nope tp 1',
      'scoreboard players set #neg tp -3',
      'execute if score #neg tp matches -5..-1 run scoreboard players set #negok tp 1',
    ].join('\n'),
  });
  const events = sim.step();
  for (const flag of ['#exact', '#min', '#max', '#range', '#all', '#unless', '#negok']) {
    assert.equal(scoreOf(sim, flag), 1, `${flag} should be set`);
  }
  assert.equal(scoreOf(sim, '#nope'), 0);
  // A failing execute condition must not emit a command event for its line.
  const texts = byType(events, 'command').map((event) => event.text);
  assert.ok(!texts.some((text) => text.includes('#nope')));
});

